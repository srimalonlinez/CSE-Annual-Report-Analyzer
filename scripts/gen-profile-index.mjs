// Regenerates src/sectors/profiles.js: static imports of every config/sector_profiles/*.json.
// Static imports work the same in the browser bundle, the Netlify function and Node tests.
// Run after adding or renaming a profile: node scripts/gen-profile-index.mjs
import fs from "node:fs";
const files=fs.readdirSync("config/sector_profiles").filter(f=>f.endsWith(".json")).sort();
const v=f=>f.replace(/\.json$/,"").replace(/^_/,"").replace(/_([a-z])/g,(_,c)=>c.toUpperCase());
const out=["// GENERATED by scripts/gen-profile-index.mjs - do not edit by hand.",
  ...files.map(f=>`import ${v(f)} from "../../config/sector_profiles/${f}" with {type:"json"};`),
  `export const CROSS=crossSector;`,
  `export const PROFILES=[${files.filter(f=>!f.startsWith("_")).map(v).join(",")}];`,""];
fs.writeFileSync("src/sectors/profiles.js",out.join("\n"));
console.log(`indexed ${files.length} files`);
